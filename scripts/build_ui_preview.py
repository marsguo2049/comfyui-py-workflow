def story_preview_stages(html: str) -> str:
    """Expose all three stages only in the public demonstration UI."""
    tabs = '<div class="workflow-strip" role="tablist" aria-label="故事视频演示阶段">'
    for key, label in [('input', '1　输入故事'), ('plan', '2　分析与分镜'), ('output', '3　生成与导出')]:
        selected = key == 'input'
        tabs += (f'<button id="story-tab-{key}" type="button" role="tab" data-story-stage="{key}" '
                 f'aria-controls="story-stage-{key}" aria-selected="{str(selected).lower()}" '
                 f'tabindex="{0 if selected else -1}" class="{"active" if selected else ""}">{label}</button>')
    tabs += '</div><p class="hint preview-stage-hint">展示模式 · 三个阶段均可直接查看，无需创建任务。</p>'
    def panel(key: str) -> str:
        return (f'<div id="story-stage-{key}" role="tabpanel" aria-labelledby="story-tab-{key}" '
                f'tabindex="0" class="{"hidden" if key != "input" else ""}">')
    replacements = [
        ('<div class="workflow-strip"><span class="active">1　输入故事</span><span>2　分析与分镜</span><span>3　生成与导出</span></div>', tabs + panel('input')),
        ('<section class="panel hidden" id="analysis-panel">', '</div>' + panel('plan') + '<section class="panel" id="analysis-panel">'),
        ('<section class="panel hidden" id="plan-panel">', '<section class="panel" id="plan-panel">'),
        ('<section class="panel hidden" id="progress-panel">', '</div>' + panel('output') + '<section class="panel" id="progress-panel">'),
        ('<section class="panel hidden" id="results-panel">', '<section class="panel" id="results-panel">'),
        ('    <div id="view-comic" class="hidden">', '    </div>\n    <div id="view-comic" class="hidden">'),
        ('<div id="analysis-empty" class="empty-state">', '<div id="analysis-empty" class="empty-state hidden">'),
        ('<div id="analysis-result" class="hidden">', '<div id="analysis-result">'),
    ]
    for before, after in replacements:
        if html.count(before) != 1:
            raise ValueError('Local story markup changed; update preview stage grouping: ' + before)
        html = html.replace(before, after, 1)
    html = re.sub(r'(<section class="panel" id="plan-panel">.*?)(<p class="hint">.*?</p>)',
                  r'\1<p class="hint">下方是公开虚构故事的分镜摘要。实际运行时，此处显示可审阅和修改的模型专用提示词与完整执行计划。</p>',
                  html, count=1, flags=re.DOTALL)
    video = '''<p class="hint">以下是仓库已有的 10 秒单车公开样片，用于演示结果播放与下载；它与上方虚构故事的 30 秒分镜独立，不是该分镜的生成结果。</p>
      <video controls preload="none" poster="assets/bicycle-frame-0001.png" aria-label="公开单车示例视频"><source src="assets/bicycle-final-10s.mp4" type="video/mp4">浏览器不支持视频播放，请下载 MP4 查看。</video>
      <p><a class="preview-download" href="assets/bicycle-final-10s.mp4" download>下载公开样片 · MP4 / 10 秒 ↓</a></p>'''
    html = html.replace('<div id="final-video"></div>', '<div id="final-video">' + video + '</div>')
    gallery = ''.join(f'<a href="assets/{name}" target="_blank" rel="noopener"><img loading="lazy" src="assets/{name}" alt="公开单车示例关键帧 {index}"></a>'
                      for index, name in enumerate(PUBLIC_MEDIA[:3], 1))
    html = html.replace('<div id="keyframe-gallery" class="gallery"></div>', '<div id="keyframe-gallery" class="gallery">' + gallery + '</div>')
    html = html.replace('<div id="clip-list" class="clip-list"></div>', '<div id="clip-list" class="clip-list"><p class="hint">本地运行后，此处列出逐段生成的视频。本预览提供上方合成样片供查看。</p></div>')
    return html


def preview_html() -> str:
    html = (WEB / "index.html").read_text(encoding="utf-8")
    html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by scripts/build_ui_preview.py; edit the local UI or preview sources. -->")
    html = html.replace('<link rel="stylesheet" href="/static/style.css">', '''<meta name="description" content="Offline Studio 统一工作台预览：故事漫画、故事视频、批量图片编辑与本机服务设置。使用公开示例，无上传或模型请求。">
  <meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'self'; style-src 'self'; img-src 'self' data:; media-src 'self'; connect-src 'none'; form-action 'none'; base-uri 'none'">
  <link rel="stylesheet" href="style.css">
  <link rel="stylesheet" href="preview.css">''')
    html = html.replace('<body>', '''<body>
  <div class="preview-notice"><strong>界面预览</strong><span>虚构示例 · 无上传、模型或后台连接</span><a href="https://github.com/marsguo2049/comfyui-py-workflow#quick-start">在本机运行 ↗</a></div>
  <noscript><p class="no-script">请启用 JavaScript 切换工作区。下面展示故事视频界面；真正处理任务请在本机运行项目。</p></noscript>''')
    html = re.sub(r'  <script src="/static/[^"\n]+"></script>\n', '', html)
    html = html.replace('</body>', '  <script src="preview.js"></script>\n</body>')
    html = story_preview_stages(html)
    # Disable real action controls in the HTML itself, even when scripts are off.
    html = re.sub(r'<(input|textarea|select)\b', r'<\1 disabled', html)
    def disable_action(match: re.Match[str]) -> str:
        tag = match.group(0)
        return tag if 'data-view=' in tag or 'data-story-stage=' in tag or 'id="go-settings"' in tag else tag.replace('<button', '<button disabled', 1)
    html = re.sub(r'<button\b[^>]*>', disable_action, html)
    html = html.replace('<span id="service-summary">检测中</span>', '<span id="service-summary">仅展示</span>')
    html = html.replace('在本机处理与保存<small>', '公开虚构示例<small>')
    html = html.replace('创作留在本机。</span>', '静态预览 · 实际任务请在本机运行。</span>')
    return html


