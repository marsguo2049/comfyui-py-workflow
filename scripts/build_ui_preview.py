def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    artifacts = {
        DOCS / "index.html": preview_html(),
        DOCS / "style.css": (WEB / "style.css").read_text(encoding="utf-8"),
        DOCS / "assets" / "comfyui-workbench-preview.svg": overview_svg(),
    }
    stale = []
    for path, content in artifacts.items():
        if args.check:
            existing = path.read_text(encoding="utf-8") if path.is_file() else None
            if existing != content:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        parser.exit(1, "Preview is stale; run python scripts/build_ui_preview.py: " + ", ".join(stale) + "\n")
    print("Public UI preview is up to date." if args.check else "Built public UI preview.")


if __name__ == "__main__":
    main()
