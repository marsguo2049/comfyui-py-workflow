"""Build the inert public ComfyUI Workbench preview. Standard library only."""
from __future__ import annotations

import argparse
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "src" / "comfyui_py_workflow" / "web"
DOCS = ROOT / "docs"


def render_local_index() -> str:
    shell = (WEB / "index.html").read_text(encoding="utf-8")
    marker = "<!-- COMFYUI_BATCH -->"
    if shell.count(marker) != 1:
        raise ValueError("Local UI must contain exactly one COMFYUI_BATCH marker")
    return shell.replace(marker, (WEB / "batch.html").read_text(encoding="utf-8"))


def preview_html() -> str:
    html = render_local_index()
    html = html.replace(
        "<!doctype html>",
        "<!doctype html>\n<!-- Generated by scripts/build_ui_preview.py; edit the local UI or preview sources. -->",
    )
    html = html.replace(
        '<link rel="stylesheet" href="/static/style.css">',
        '''<meta name="description" content="ComfyUI Workbench 批量图片与首尾帧视频静态预览。使用虚构文件名，无上传或模型请求。">
  <meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'self'; style-src 'self'; img-src 'self' data:; media-src 'self'; connect-src 'none'; form-action 'none'; base-uri 'none'">
  <link rel="stylesheet" href="style.css">
  <link rel="stylesheet" href="preview.css">''',
    )
    html = html.replace(
        "<body>",
        '''<body>
  <div class="preview-notice"><strong>界面预览</strong><span>虚构配对示例 · 无上传、模型或后台连接</span><a href="https://github.com/marsguo2049/comfyui-py-workflow#quick-start">在本机运行 ↗</a></div>
  <noscript><p class="no-script">请启用 JavaScript 切换批量工具。真正处理任务请在本机运行项目。</p></noscript>''',
    )
    html = re.sub(r'  <script src="/static/[^"\n]+"></script>\n', "", html)
    html = html.replace("</body>", '  <script src="preview.js"></script>\n</body>')
    html = re.sub(r'<(input|textarea|select)\b', r'<\1 disabled', html)
    html = html.replace('<select disabled id="batch-tool">', '<select id="batch-tool">')

    def disable_action(match: re.Match[str]) -> str:
        tag = match.group(0)
        return tag if "data-view=" in tag or 'id="go-settings"' in tag else tag.replace("<button", "<button disabled", 1)

    html = re.sub(r"<button\b[^>]*>", disable_action, html)
    html = html.replace('<span id="service-summary">检测中</span>', '<span id="service-summary">仅展示</span>')
    html = html.replace('<article class="status-card" id="comfy-status"><strong>ComfyUI</strong><p>尚未检测</p></article>',
                        '<article class="status-card" id="comfy-status"><strong>ComfyUI</strong><p>预览模式，不检测本机服务。</p></article>')
    html = html.replace('在本机处理与保存<small>', '公开虚构示例<small>')
    html = html.replace('批量任务留在本机。</span>', '静态预览 · 实际任务请在本机运行。</span>')
    html = html.replace('<option value="first-last-video">', '<option value="first-last-video" selected>')
    html = html.replace('<div id="batch-video-inputs" class="hidden">', '<div id="batch-video-inputs">')
    html = html.replace('<div id="batch-drop" class="drop-zone">', '<div id="batch-drop" class="drop-zone hidden">')
    html = html.replace(
        '<div id="batch-pair-preview" class="selection-list" aria-live="polite"></div>',
        '''<div id="batch-pair-preview" class="selection-list" aria-live="polite">
                <div class="selection-row">1. sample-start-01.png → sample-end-01.png</div>
                <div class="selection-row">2. sample-start-02.png → sample-end-02.png</div>
              </div>''',
    )
    html = html.replace('<strong id="batch-first-count">尚未选择</strong>', '<strong id="batch-first-count">已选择 2 张 · 示例</strong>')
    html = html.replace('<strong id="batch-last-count">尚未选择</strong>', '<strong id="batch-last-count">已选择 2 张 · 示例</strong>')
    html = html.replace('<p id="batch-duration-hint" class="hint"></p>', '<p id="batch-duration-hint" class="hint">预计每段 5.17 秒 · 125 帧 / 24 fps · 共 2 段</p>')
    return html


